#!/usr/bin/env python3
"""Training-only recursive SHAP feature elimination for CIC-MalMem experiments.
Run this only after run_experiments.py has created a development/test split.csv.
The locked test rows are never used for ranking.
"""
import argparse, json
from pathlib import Path
import numpy as np
import pandas as pd
import shap
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler, LabelEncoder


def normalize_family(v):
    s=str(v).strip()
    if 'benign' in s.lower(): return 'Benign'
    for sep in ['-','_',':']:
        p=s.split(sep)
        if len(p)>=2 and p[0].lower() in {'ransomware','spyware','trojan','trojanhorse'}:
            return p[0]+'-'+p[1]
    return s


def mean_abs_shap(values):
    """Return per-feature mean absolute SHAP robustly across SHAP output shapes."""
    if isinstance(values, list):
        arr=np.stack([np.asarray(v) for v in values],axis=0)  # class,sample,feature
        return np.mean(np.abs(arr),axis=(0,1))
    arr=np.asarray(values)
    if arr.ndim==2: return np.mean(np.abs(arr),axis=0)
    if arr.ndim==3:
        # Common layouts: sample,feature,class or sample,class,feature.
        if arr.shape[1] <= arr.shape[2]:
            return np.mean(np.abs(arr),axis=(0,2))
        return np.mean(np.abs(arr),axis=(0,1))
    raise ValueError(f'Unexpected SHAP shape: {arr.shape}')


def recursive_select(X,y,k,seed=20260911,max_explain=2500):
    imputer=SimpleImputer(strategy='median',keep_empty_features=True)
    scaler=StandardScaler()
    Z=scaler.fit_transform(imputer.fit_transform(X))
    Z=pd.DataFrame(Z,columns=X.columns,index=X.index)
    features=list(Z.columns)
    history=[]
    rng=np.random.default_rng(seed)

    while len(features)>k:
        model=RandomForestClassifier(
            n_estimators=500,random_state=seed,n_jobs=-1,
            class_weight='balanced_subsample',max_features='sqrt'
        )
        model.fit(Z[features],y)

        # Explanation subset is selected only from development/training data.
        if len(Z)>max_explain:
            idx=rng.choice(len(Z),size=max_explain,replace=False)
            Xe=Z.iloc[idx][features]
        else:
            Xe=Z[features]

        explainer=shap.TreeExplainer(model)
        vals=explainer.shap_values(Xe,check_additivity=False)
        imp=mean_abs_shap(vals)
        if len(imp)!=len(features):
            raise RuntimeError(f'Importance length {len(imp)} != features {len(features)}')
        ranking=sorted(zip(features,imp),key=lambda t:t[1])
        removed=ranking[0][0]
        history.append({
            'n_features_before':len(features),
            'removed':removed,
            'importance':float(ranking[0][1]),
            'ranking':[{"feature":f,"mean_abs_shap":float(v)} for f,v in ranking]
        })
        features.remove(removed)
        print(f'{len(features):02d} remain; removed {removed}')
    return features,history


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--csv',required=True,type=Path)
    ap.add_argument('--split',required=True,type=Path,help='split.csv generated by run_experiments.py')
    ap.add_argument('--task',choices=['binary','family'],default='family')
    ap.add_argument('--k',type=int,default=7)
    ap.add_argument('--out',type=Path,default=Path('outputs/shap_rfe'))
    ap.add_argument('--seed',type=int,default=20260911)
    a=ap.parse_args(); a.out.mkdir(parents=True,exist_ok=True)

    df=pd.read_csv(a.csv); split=pd.read_csv(a.split)
    if len(df)!=len(split): raise ValueError('CSV and split row counts differ')
    low={c.lower():c for c in df.columns}; cls=low.get('class',low.get('label')); cat=low.get('category')
    if cls is None: raise ValueError('Need Class or Label column')
    dev=split['split'].eq('development').to_numpy()
    drop=[cls]+([cat] if cat else [])
    X=df.drop(columns=drop,errors='ignore').select_dtypes(include=[np.number]).replace([np.inf,-np.inf],np.nan)
    if a.task=='binary':
        ystr=df[cls].astype(str).str.lower().map(lambda s:'Benign' if ('benign' in s or s in {'0','false'}) else 'Malware')
    else:
        if cat is None: raise ValueError('Family task requires Category column')
        ystr=df[cat].map(normalize_family)
    le=LabelEncoder(); y=le.fit_transform(ystr[dev])
    selected,history=recursive_select(X.loc[dev],y,a.k,a.seed)
    (a.out/f'selected_k{a.k}.json').write_text(json.dumps({'task':a.task,'k':a.k,'selected_features':selected,'label_classes':list(le.classes_)},indent=2),encoding='utf8')
    (a.out/f'history_k{a.k}.json').write_text(json.dumps(history,indent=2),encoding='utf8')
    print('Selected:',selected)

if __name__=='__main__': main()
